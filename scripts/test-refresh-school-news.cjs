/* Offline validation of safe official QNA RSS parsing and headline selection. */
"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const {parseFeed,safeArticleUrl,decodeXml}=require("./refresh-school-news.cjs");
const fixture=fs.readFileSync("scripts/fixtures/qna-schools-sample.xml","utf8");
const frozen=new Date("2026-10-18T16:00:00Z");
const result=parseFeed(fixture,frozen);
assert.equal(result.schema,1);
assert.equal(result.headlines.length,2,"Only two official, school-related headlines are permitted");
assert(result.headlines.every(n=>n.url.startsWith("https://qna.org.qa/en/News-Area/News/")));
assert(result.headlines.some(n=>n.title.includes("Teaching and Learning")));
assert(result.headlines.some(n=>n.title.includes("Student Research")));
assert(!result.headlines.some(n=>n.title.includes("Strategic Dialogue")));
assert(!result.headlines.some(n=>n.title.includes("emergency")));
assert(result.headlines[0].publishedAt>result.headlines[1].publishedAt,"Newest story first");
assert(result.headlines.some(n=>n.title.includes("Innovation & Collaboration")),"Must decode XML entities safely");
assert(!safeArticleUrl("https://qna.org.qa.evil.example/en/News-Area/News/2026-10/18/fake"));
assert(!safeArticleUrl("javascript:alert(1)"));
assert(!safeArticleUrl("https://qna.org.qa@evil.example/en/News-Area/News/2026-10/18/fake"));
assert(!safeArticleUrl("https://qna.org.qa/en/home"));
assert.equal(decodeXml("&lt;teacher&gt;"),"<teacher>");
assert.throws(()=>parseFeed("not rss",frozen));
const tooOld=parseFeed(fixture,new Date("2027-04-20T12:00:00Z"));
assert.equal(tooOld.headlines.length,0,"Exclude stale articles from new snapshots");
const initial=JSON.parse(fs.readFileSync("school-live-news.json","utf8"));
assert.equal(initial.lastSuccessfulFetch,null,"Review branch must not impersonate a successful live feed");
console.log("PASS: QNA RSS safe parser, education-only titles, official article links, freshness and explicit no-feed initial status");
